-- ============================================================================
-- FleetTrack Logistics OS - Database Schema DDL
-- Target RDBMS: Oracle Database 11g XE / 19c / 21c (Enterprise Schema)
-- ============================================================================

-- 1. App Users (RBAC: ADMIN, DISPATCHER, FLEET_MANAGER)
CREATE TABLE APP_USERS (
    USER_ID NUMBER(10) PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(30) DEFAULT 'DISPATCHER' NOT NULL,
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

-- 2. Fleet Vehicles
CREATE TABLE VEHICLES (
    VEHICLE_ID NUMBER PRIMARY KEY,
    REGISTRATION_NO VARCHAR2(20) NOT NULL UNIQUE,
    VEHICLE_NAME VARCHAR2(60) NOT NULL,
    VEHICLE_TYPE VARCHAR2(30) NOT NULL, -- HEAVY_DUTY, MEDIUM_TRANSIT, ELECTRIC_VAN, LIGHT_CARGO
    DAILY_RATE NUMBER(10,2) NOT NULL,
    VEHICLE_STATUS VARCHAR2(20) NOT NULL -- AVAILABLE, RENTED, MAINTENANCE, ON_ROUTE
);

-- 3. Commercial Fleet Drivers
CREATE TABLE DRIVERS (
    DRIVER_ID NUMBER(10) PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20) NOT NULL UNIQUE,
    LICENSE_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    LICENSE_EXPIRY DATE,
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE' -- ACTIVE, ON_DUTY, ON_LEAVE, SUSPENDED
);

-- 4. Freight Shipments & Consignments
CREATE TABLE SHIPMENTS (
    SHIPMENT_ID NUMBER(10) PRIMARY KEY,
    TRACKING_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    CUSTOMER_NAME VARCHAR2(100),
    CUSTOMER_PHONE VARCHAR2(20),
    PICKUP_ADDRESS VARCHAR2(300) NOT NULL,
    DELIVERY_ADDRESS VARCHAR2(300) NOT NULL,
    WEIGHT_KG NUMBER(12,2),
    STATUS VARCHAR2(30) DEFAULT 'CREATED', -- CREATED, ASSIGNED, IN_TRANSIT, DELIVERED, CANCELLED
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    EXPECTED_DELIVERY DATE
);

-- 5. Trip / Consignment Assignments
CREATE TABLE ASSIGNMENTS (
    ASSIGNMENT_ID NUMBER(10) PRIMARY KEY,
    SHIPMENT_ID NUMBER(10) NOT NULL,
    DRIVER_ID NUMBER(10) NOT NULL,
    VEHICLE_ID NUMBER(10) NOT NULL,
    ASSIGNED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR2(30) DEFAULT 'PENDING',
    CONSTRAINT FK_ASGN_SHIPMENT FOREIGN KEY (SHIPMENT_ID) REFERENCES SHIPMENTS(SHIPMENT_ID),
    CONSTRAINT FK_ASGN_DRIVER FOREIGN KEY (DRIVER_ID) REFERENCES DRIVERS(DRIVER_ID),
    CONSTRAINT FK_ASGN_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(VEHICLE_ID)
);

-- 6. Corridor Transit Routes
CREATE TABLE ROUTES (
    ROUTE_ID NUMBER(10) PRIMARY KEY,
    ASSIGNMENT_ID NUMBER(10) NOT NULL,
    ROUTE_NAME VARCHAR2(100),
    START_LOCATION VARCHAR2(200),
    END_LOCATION VARCHAR2(200),
    DISTANCE_KM NUMBER(10,2),
    ESTIMATED_MINUTES NUMBER(10),
    STATUS VARCHAR2(30) DEFAULT 'ACTIVE',
    CONSTRAINT FK_ROUTE_ASGN FOREIGN KEY (ASSIGNMENT_ID) REFERENCES ASSIGNMENTS(ASSIGNMENT_ID)
);

-- 7. Route Transit Stops / Waypoints
CREATE TABLE ROUTE_STOPS (
    STOP_ID NUMBER(10) PRIMARY KEY,
    ROUTE_ID NUMBER(10) NOT NULL,
    STOP_ORDER NUMBER(5) NOT NULL,
    LOCATION_NAME VARCHAR2(200) NOT NULL,
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    ARRIVAL_TIME TIMESTAMP(6),
    CONSTRAINT FK_STOP_ROUTE FOREIGN KEY (ROUTE_ID) REFERENCES ROUTES(ROUTE_ID)
);

-- 8. Real-time Telematics GPS Coordinates
CREATE TABLE VEHICLE_LOCATIONS (
    LOCATION_ID NUMBER(10) PRIMARY KEY,
    VEHICLE_ID NUMBER(10) NOT NULL,
    LATITUDE NUMBER(10,7) NOT NULL,
    LONGITUDE NUMBER(10,7) NOT NULL,
    RECORDED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_LOC_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(VEHICLE_ID)
);

-- 9. Fuel & Energy Expenses
CREATE TABLE FUEL_RECORDS (
    FUEL_ID NUMBER(10) PRIMARY KEY,
    VEHICLE_ID NUMBER(10) NOT NULL,
    FUEL_DATE DATE NOT NULL,
    FUEL_TYPE VARCHAR2(30) NOT NULL, -- DIESEL, CNG, ELECTRIC, PETROL
    LITRES NUMBER(10,2) NOT NULL,
    PRICE_PER_LITRE NUMBER(10,2) NOT NULL,
    TOTAL_COST NUMBER(12,2) NOT NULL,
    ODOMETER_READING NUMBER(12,2),
    FUEL_STATION VARCHAR2(100),
    CONSTRAINT FK_FUEL_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(VEHICLE_ID)
);

-- 10. Vehicle Maintenance & Preventive Servicing
CREATE TABLE MAINTENANCE (
    MAINTENANCE_ID NUMBER PRIMARY KEY,
    VEHICLE_ID NUMBER NOT NULL,
    MAINTENANCE_DATE DATE NOT NULL,
    DESCRIPTION VARCHAR2(200) NOT NULL,
    COST NUMBER(10,2) NOT NULL,
    MAINTENANCE_STATUS VARCHAR2(20) NOT NULL, -- SCHEDULED, IN_PROGRESS, COMPLETED
    CONSTRAINT FK_MAINT_VEHICLE FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLES(VEHICLE_ID)
);

-- 11. Shipment Status Audit History
CREATE TABLE SHIPMENT_STATUS_HISTORY (
    HISTORY_ID NUMBER(10) PRIMARY KEY,
    SHIPMENT_ID NUMBER(10) NOT NULL,
    OLD_STATUS VARCHAR2(30),
    NEW_STATUS VARCHAR2(30) NOT NULL,
    CHANGED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    REMARKS VARCHAR2(500),
    CONSTRAINT FK_HIST_SHIPMENT FOREIGN KEY (SHIPMENT_ID) REFERENCES SHIPMENTS(SHIPMENT_ID)
);

-- 12. Security & Operational Audit Log
CREATE TABLE AUDIT_LOGS (
    AUDIT_ID NUMBER(10) PRIMARY KEY,
    USER_ID NUMBER(10),
    ACTION VARCHAR2(100) NOT NULL,
    ENTITY_NAME VARCHAR2(100),
    ENTITY_ID NUMBER(10),
    DETAILS VARCHAR2(1000),
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);
